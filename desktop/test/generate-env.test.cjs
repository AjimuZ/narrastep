// Tests of scripts/generate-env.sh with fixed hardware: every row of the ADR 0016 table, unknown values, busy ports, the low-memory warning and the absence of network tools.
'use strict';

const assert = require('node:assert/strict');
const childProcess = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const { afterEach, beforeEach, describe, it } = require('node:test');

const ROOT = path.resolve(__dirname, '..', '..');
const SCRIPT = path.join(ROOT, 'scripts', 'generate-env.sh');
const ADR = path.join(
  ROOT,
  'docs',
  'decisions',
  '0016-podman-generated-environment-and-dependency-refresh.md',
);

// The generator is a POSIX shell script; on Windows it runs in Git Bash, which this suite does not drive.
const skip = process.platform === 'win32' ? 'generate-env.sh is exercised on POSIX shells' : false;

const FIXED = {
  NARRASTEP_PROBE_HOST_CPUS: '8',
  NARRASTEP_PROBE_HOST_MEMORY_MB: '16384',
  NARRASTEP_PROBE_ENGINE_CPUS: '',
  NARRASTEP_PROBE_ENGINE_MEMORY_MB: '',
  NARRASTEP_PROBE_FREE_DISK_MB: '200000',
  NARRASTEP_PROBE_LISTENING_PORTS: '',
  NARRASTEP_PROBE_DATE: '2026-01-02',
};

let work;

beforeEach(() => {
  // Inside the repository rather than os.tmpdir(): fake commands must be executable (see start-script.test.cjs).
  work = fs.mkdtempSync(path.join(__dirname, '.generate-env-test-'));
});

afterEach(() => {
  fs.rmSync(work, { recursive: true, force: true });
});

/** Runs the generator with fixed hardware overridden by `env`; returns stdout, status and the key map. */
function generate(env = {}, args = [], pathPrefix = '') {
  const result = childProcess.spawnSync('sh', [SCRIPT, ...args], {
    encoding: 'utf8',
    env: {
      ...process.env,
      ...FIXED,
      ...env,
      PATH: pathPrefix ? `${pathPrefix}:${process.env.PATH}` : process.env.PATH,
    },
  });
  const values = {};
  for (const line of result.stdout.split('\n')) {
    const match = /^([A-Z_]+)=(.*)$/.exec(line);
    if (match) values[match[1]] = match[2];
  }
  return { stdout: result.stdout, stderr: result.stderr, status: result.status, values };
}

/** Writes an executable fake command into the work folder and returns that folder. */
function writeTool(name, body) {
  fs.writeFileSync(path.join(work, name), `#!/bin/sh\n${body}\n`, { mode: 0o755 });
  return work;
}

describe('generate-env.sh', { skip }, () => {
  it('prints a complete .env on standard output and writes nothing', () => {
    const before = fs.readdirSync(ROOT).sort();
    const { status, stdout, values } = generate();
    assert.equal(status, 0);
    assert.match(stdout, /^# Generated by scripts\/generate-env.sh on 2026-01-02\./);
    for (const key of [
      'NARRASTEP_WHISPER_MODEL',
      'NARRASTEP_WHISPER_DEVICE',
      'NARRASTEP_WHISPER_COMPUTE_TYPE',
      'NARRASTEP_WHISPER_CPU_THREADS',
      'NARRASTEP_MAX_UPLOAD_SIZE_MB',
      'NARRASTEP_MIN_FREE_DISK_MB',
      'NARRASTEP_WEB_PORT',
      'NARRASTEP_API_PORT',
      'NARRASTEP_CORS_ORIGINS',
    ]) {
      assert.ok(key in values, `${key} is missing`);
    }
    assert.deepEqual(fs.readdirSync(ROOT).sort(), before);
  });

  describe('model tiers', () => {
    const cases = [
      [2047, 8, 'tiny'],
      [3071, 8, 'tiny'],
      [3072, 8, 'base'],
      [6143, 8, 'base'],
      [6144, 8, 'small'],
      [12287, 8, 'small'],
      [12288, 6, 'medium'],
      [32768, 16, 'medium'],
      [12288, 4, 'small'],
    ];
    for (const [memory, cpus, model] of cases) {
      it(`${memory} MB and ${cpus} CPUs choose ${model}`, () => {
        const { values } = generate({
          NARRASTEP_PROBE_HOST_MEMORY_MB: String(memory),
          NARRASTEP_PROBE_HOST_CPUS: String(cpus),
        });
        assert.equal(values.NARRASTEP_WHISPER_MODEL, model);
      });
    }

    it('takes the smaller of the engine and host memory', () => {
      const { values, stdout } = generate({ NARRASTEP_PROBE_ENGINE_MEMORY_MB: '2000' });
      assert.equal(values.NARRASTEP_WHISPER_MODEL, 'tiny');
      assert.match(stdout, /Usable memory: 2000 MB/);
    });

    it('takes the smaller CPU count of the engine and the host', () => {
      const { values } = generate({ NARRASTEP_PROBE_ENGINE_CPUS: '2' });
      assert.equal(values.NARRASTEP_WHISPER_CPU_THREADS, '2');
      assert.equal(values.NARRASTEP_WHISPER_MODEL, 'small');
    });
  });

  it('always uses cpu and int8', () => {
    const { values } = generate();
    assert.equal(values.NARRASTEP_WHISPER_DEVICE, 'cpu');
    assert.equal(values.NARRASTEP_WHISPER_COMPUTE_TYPE, 'int8');
  });

  describe('CPU threads', () => {
    const cases = [
      [1, '1'],
      [2, '2'],
      [3, '3'],
      [4, '3'],
      [8, '7'],
      [17, '16'],
      [18, '16'],
      [64, '16'],
    ];
    for (const [cpus, threads] of cases) {
      it(`${cpus} CPUs give ${threads} threads`, () => {
        const { values } = generate({ NARRASTEP_PROBE_HOST_CPUS: String(cpus) });
        assert.equal(values.NARRASTEP_WHISPER_CPU_THREADS, threads);
      });
    }
  });

  describe('upload limit', () => {
    const cases = [
      ['200000', '4096'],
      ['16384', '4096'],
      ['16383', '4095'],
      ['8000', '2000'],
      ['1000', '512'],
      ['0', '512'],
    ];
    for (const [disk, upload] of cases) {
      it(`${disk} MB free give an upload limit of ${upload} MB`, () => {
        const { values } = generate({ NARRASTEP_PROBE_FREE_DISK_MB: disk });
        assert.equal(values.NARRASTEP_MAX_UPLOAD_SIZE_MB, upload);
        assert.equal(values.NARRASTEP_MIN_FREE_DISK_MB, '1024');
      });
    }
  });

  describe('ports and CORS', () => {
    it('keeps the default ports when they are free', () => {
      const { values } = generate();
      assert.equal(values.NARRASTEP_WEB_PORT, '4200');
      assert.equal(values.NARRASTEP_API_PORT, '8002');
      assert.equal(values.NARRASTEP_CORS_ORIGINS, 'http://127.0.0.1:4200,http://localhost:4200');
    });

    it('moves a busy web port to the next free one, rebuilds CORS and says so', () => {
      const { values, stdout } = generate({ NARRASTEP_PROBE_LISTENING_PORTS: '4200 4201 22' });
      assert.equal(values.NARRASTEP_WEB_PORT, '4202');
      assert.equal(values.NARRASTEP_API_PORT, '8002');
      assert.equal(values.NARRASTEP_CORS_ORIGINS, 'http://127.0.0.1:4202,http://localhost:4202');
      assert.match(stdout, /# NARRASTEP_WEB_PORT=4202: 4200 is in use/);
    });

    it('moves a busy API port', () => {
      const { values, stdout } = generate({ NARRASTEP_PROBE_LISTENING_PORTS: '8002' });
      assert.equal(values.NARRASTEP_API_PORT, '8003');
      assert.match(stdout, /# NARRASTEP_API_PORT=8003: 8002 is in use/);
    });

    it('keeps the default when no port within 20 steps is free', () => {
      const ports = Array.from({ length: 21 }, (_, i) => 4200 + i).join(' ');
      const { values } = generate({ NARRASTEP_PROBE_LISTENING_PORTS: ports });
      assert.equal(values.NARRASTEP_WEB_PORT, '4200');
    });

    it('uses the 20th step above the default', () => {
      const ports = Array.from({ length: 20 }, (_, i) => 4200 + i).join(' ');
      const { values } = generate({ NARRASTEP_PROBE_LISTENING_PORTS: ports });
      assert.equal(values.NARRASTEP_WEB_PORT, '4220');
    });
  });

  describe('unknown values', () => {
    it('uses the defaults and says unknown when nothing can be measured', () => {
      const { values, stdout } = generate({
        NARRASTEP_PROBE_HOST_CPUS: '',
        NARRASTEP_PROBE_HOST_MEMORY_MB: '',
        NARRASTEP_PROBE_FREE_DISK_MB: '',
      });
      assert.equal(values.NARRASTEP_WHISPER_MODEL, 'small');
      assert.equal(values.NARRASTEP_MAX_UPLOAD_SIZE_MB, '4096');
      assert.ok(!('NARRASTEP_WHISPER_CPU_THREADS' in values));
      assert.match(
        stdout,
        /CPUs host unknown, engine unknown; memory host unknown MB, engine unknown MB/,
      );
      assert.match(stdout, /NARRASTEP_WHISPER_CPU_THREADS is not set/);
      assert.doesNotMatch(stdout, /WARNING/);
    });

    it('treats a non-numeric value as unknown', () => {
      const { values } = generate({ NARRASTEP_PROBE_HOST_MEMORY_MB: 'lots' });
      assert.equal(values.NARRASTEP_WHISPER_MODEL, 'small');
    });

    it('does not pick medium when the CPU count is unknown', () => {
      const { values } = generate({
        NARRASTEP_PROBE_HOST_MEMORY_MB: '32768',
        NARRASTEP_PROBE_HOST_CPUS: '',
      });
      assert.equal(values.NARRASTEP_WHISPER_MODEL, 'small');
    });
  });

  describe('low-memory warning', () => {
    it('warns below 6 GB and explains how to raise the limit', () => {
      const { stdout, values } = generate({ NARRASTEP_PROBE_HOST_MEMORY_MB: '4096' });
      assert.equal(values.NARRASTEP_WHISPER_MODEL, 'base');
      assert.match(stdout, /# WARNING: only 4096 MB of memory is usable/);
      assert.match(stdout, /Docker Desktop/);
      assert.match(stdout, /podman machine set --memory/);
    });

    it('does not warn at 6 GB', () => {
      const { stdout } = generate({ NARRASTEP_PROBE_HOST_MEMORY_MB: '6144' });
      assert.doesNotMatch(stdout, /WARNING/);
    });

    it('warns when the engine limit is lower than the host memory', () => {
      const { stdout } = generate({ NARRASTEP_PROBE_ENGINE_MEMORY_MB: '2048' });
      assert.match(stdout, /# WARNING: only 2048 MB/);
    });
  });

  describe('engine probe', () => {
    it('reads CPUs and memory from a fake docker', () => {
      const bin = writeTool(
        'docker',
        'case "$3" in "{{.NCPU}}") echo 2;; "{{.MemTotal}}") echo 2147483648;; esac',
      );
      const { values, stdout } = generate(
        { NARRASTEP_PROBE_ENGINE_CPUS: undefined, NARRASTEP_PROBE_ENGINE_MEMORY_MB: undefined },
        ['--engine', 'docker'],
        bin,
      );
      assert.match(stdout, /engine 2; memory host 16384 MB, engine 2048 MB/);
      assert.equal(values.NARRASTEP_WHISPER_MODEL, 'tiny');
      assert.equal(values.NARRASTEP_WHISPER_CPU_THREADS, '2');
    });

    it('reads a fake podman', () => {
      const bin = writeTool(
        'podman',
        'case "$3" in "{{.Host.CPUs}}") echo 4;; "{{.Host.MemTotal}}") echo 4294967296;; esac',
      );
      const { values } = generate(
        { NARRASTEP_PROBE_ENGINE_CPUS: undefined, NARRASTEP_PROBE_ENGINE_MEMORY_MB: undefined },
        ['--engine', 'podman'],
        bin,
      );
      assert.equal(values.NARRASTEP_WHISPER_MODEL, 'base');
      assert.equal(values.NARRASTEP_WHISPER_CPU_THREADS, '3');
    });

    it('treats a failing engine as unknown', () => {
      const bin = writeTool('docker', 'exit 1');
      const { values, stdout, status } = generate(
        { NARRASTEP_PROBE_ENGINE_CPUS: undefined, NARRASTEP_PROBE_ENGINE_MEMORY_MB: undefined },
        ['--engine', 'docker'],
        bin,
      );
      assert.equal(status, 0);
      assert.match(stdout, /engine unknown/);
      assert.equal(values.NARRASTEP_WHISPER_MODEL, 'medium');
    });
  });

  it('rejects an unknown argument or engine', () => {
    assert.equal(generate({}, ['--nope']).status, 2);
    assert.equal(generate({}, ['--engine', 'lxc']).status, 2);
  });

  it('calls no network tool, even when probing the real machine', () => {
    const record = path.join(work, 'network-calls.txt');
    const names = [
      'curl',
      'wget',
      'nc',
      'ncat',
      'netcat',
      'telnet',
      'ping',
      'ssh',
      'socat',
      'dig',
      'nslookup',
      'host',
      'ftp',
    ];
    for (const name of names) {
      writeTool(name, `echo "${name} $*" >> '${record}'\nexit 1`);
    }
    const unset = Object.fromEntries(
      Object.keys(FIXED)
        .filter((k) => k !== 'NARRASTEP_PROBE_DATE')
        .map((k) => [k, undefined]),
    );
    const { status, values } = generate(unset, [], work);
    assert.equal(status, 0);
    assert.ok('NARRASTEP_WHISPER_MODEL' in values);
    assert.equal(
      fs.existsSync(record),
      false,
      fs.existsSync(record) ? fs.readFileSync(record, 'utf8') : '',
    );
  });

  it('contains no network tool in the script text', () => {
    const text = fs.readFileSync(SCRIPT, 'utf8').replace(/^\s*#.*$/gm, '');
    assert.doesNotMatch(
      text,
      /\b(curl|wget|nc|ncat|netcat|telnet|ping|ssh|socat|dig|nslookup|ftp)\b|\/dev\/(tcp|udp)/,
    );
  });

  it('keeps the ADR 0016 table in step with the code', () => {
    const adr = fs.readFileSync(ADR, 'utf8');
    const { values } = generate();
    for (const key of Object.keys(values)) {
      if (['NARRASTEP_ENV', 'NARRASTEP_LOG_LEVEL', 'NARRASTEP_MIN_FREE_DISK_MB'].includes(key))
        continue;
      assert.ok(adr.includes(`\`${key}\``), `ADR 0016 does not mention ${key}`);
    }
    assert.match(
      adr,
      /`tiny` below 3 GB of usable memory, `base` from 3 GB, `small` from 6 GB, `medium` from 12 GB with at least 6 CPUs/,
    );
    assert.match(adr, /All CPUs up to 3, otherwise CPUs minus one, at most 16/);
    assert.match(
      adr,
      /lowered to a quarter of the free disk when that is smaller \(at least 512 MB\)/,
    );
    assert.match(adr, /at most 20 steps/);
  });
});
